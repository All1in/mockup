/**
 * Контракт файлового сховища.
 *
 * Навмисно вужчий за можливості S3: рівно чотири операції, які потрібні
 * застосунку. Кожен метод, доданий «про запас», — це метод, який доведеться
 * реалізувати в кожному драйвері й підтримувати вічно.
 *
 * Реалізації живуть у цій же директорії. Решта коду про існування S3 не знає:
 * api.routes.ts бачить лише цей інтерфейс, і саме тому зміна провайдера
 * (R2 → S3 → MinIO) не зачіпає жодного рядка бізнес-логіки.
 */

/** Логічна група об'єктів. Визначає префікс ключа й політику доступу. */
export type StorageScope = 'avatars' | 'company-docs';

export interface PutObjectInput {
  scope: StorageScope;
  /** Ім'я файла в межах scope, вже безпечне (uuid + розширення). */
  name: string;
  body: Buffer;
  contentType: string;
}

export interface FileStorage {
  /**
   * Кладе об'єкт і повертає його **ключ** — не URL.
   *
   * Різниця принципова. URL змінюється разом із доменом, провайдером і схемою
   * підпису; ключ не змінюється ніколи. У БД має лежати те, що не протухає, —
   * інакше зміна CDN перетворюється на міграцію всієї колекції users.
   */
  put(input: PutObjectInput): Promise<string>;

  /**
   * Тимчасове посилання на приватний об'єкт.
   *
   * TTL коротка свідомо: посилання витікає в HTML, в історію браузера, в
   * логи проксі. Довгоживуче підписане посилання — це той самий публічний
   * доступ, тільки з відкладеним терміном.
   */
  signedUrl(key: string, expiresInSeconds: number): Promise<string>;

  delete(key: string): Promise<void>;

  /** Чи існує об'єкт. Потрібно міграції, щоб бути ідемпотентною. */
  exists(key: string): Promise<boolean>;
}

/** Ключі, збережені до переїзду в об'єктне сховище, мають вигляд `/uploads/x.png`. */
export function isLegacyDiskPath(value: string): boolean {
  return value.startsWith('/uploads/');
}
